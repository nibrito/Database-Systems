Create table Branch(
  branch_id int identity(1,1) Primary key  ,
  branch_name  varchar(100) not null,
  location varchar(150) not null,
  phone varchar(20),
  opening_time time,
  closing_time time,
  branch_status VARCHAR(20) NOT NULL DEFAULT 'Active'
