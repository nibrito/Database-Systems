Create Trigger Inventory_UpdateTimestamp
On Inventory
After update
as
Begin
   Set Nocount On;
   Update Inventory
   Set last_updated = GETDATE()
   From Inventory i
   Inner Join inserted ins On i.inventory_id = ins.inventory_id;
End;
Go

Create Trigger OrderItem_UpdateOrderTotal
On OrderItem
After Insert, Update, delete
As
Begin
   Set NoCount On;

   Declare @AffectedOrders Table (order_id int);

   Insert Into @AffectedOrders (order_id)
   Select order_id From inserted
   Union
   Select order_id From deleted;

   Update Orders 
   Set total_amount = (
       Select ISNULL( Sum(oi.quantity * oi.unit_price), 0)
       From OrderItem oi
       Where oi.order_id = Orders.order_id
    )
    Where order_id IN (Select order_id from @AffectedOrders);
End;
Go

Create Trigger OrderItem_DeductInventory
On OrderItem
After Insert
As
Begin
   Set NoCount On;
   Update inv
   Set inv.quantity_in_stock = inv.quantity_in_stock - (ins.quantity * fi.quantity_required),
       inv.last_updated = GETDATE()
   From Inventory inv
   Inner Join inserted ins On 1 = 1
   Inner Join Orders o On o.order_id = ins.order_id
   Inner Join Food_Ingredient fi On fi.food_id = ins.food_id
   Where inv.branch_id = o.branch_id and inv.ingredient_id = fi.ingredient_id;
End;

Go

Create Trigger Orders_RestockOnCancel
On Orders
After Update
As
Begin
  Set NoCount On;

  If not exists(
       Select 1
       From inserted i
       join deleted d on i.order_id = d. order_id
       Where i.order_status = 'cancelled' And d.order_status <> 'cancelled'
    )
    Return;

    Update inv
    set inv.quantity_in_stock = inv.quantity_in_stock + (oi.quantity * fi.quantity_required),
        inv.last_updated = GETDATE()
    from Inventory inv
    Inner Join inserted i On 1 = 1
    Inner Join deleted d On d.order_id  = i.order_id
    Inner Join OrderItem oi On oi.order_id = i.order_id
    Inner Join Food_Ingredient fi On fi.food_id = oi.food_id
    Where i.order_status = 'cancelled' and d.order_status <> 'cancelled'
    and inv.branch_id = i.branch_id and inv.ingredient_id = fi.ingredient_id;
End;

Go

