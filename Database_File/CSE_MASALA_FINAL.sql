Create table Employee(
  employee_id int identity(1,1) primary key,
  branch_id int not null,
  manager_id int,
  name varchar(100) not null,
  phone varchar(20) Unique,
  email varchar(100) Unique,
  position varchar(50),
  salary decimal(10,2),
  hire_date date,
